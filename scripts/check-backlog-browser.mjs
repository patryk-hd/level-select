async function context({ seed=false, ownedSample=false, wishSample=false }={}) {
  const context = await browser.newContext({acceptDownloads:true});
  context.on('page',page=>page.on('pageerror',error=>errors.push(error.message)));
  await context.route('**/*',async route=>{
    const url = route.request().url(); if(!url.startsWith(`${origin}/`))return route.abort();
    const path = new URL(url).pathname.slice('/retro/'.length);
    if(path.includes('..'))return route.abort();
    try {
      let body = await readFile(new URL(`../dist/${path}`,import.meta.url));
      if(path==='library/data/library-data.js'&&!ownedSample)body=Buffer.from(body.toString().replace('window.PLAYNITE_SAMPLE = true','window.PLAYNITE_SAMPLE = false'));
      if(path==='library/data/wishlist-data.js'&&!wishSample)body=Buffer.from(body.toString().replace('window.WISHLIST_SAMPLE = true','window.WISHLIST_SAMPLE = false'));
      const type = path.endsWith('.js')?'text/javascript':path.endsWith('.css')?'text/css':path.endsWith('.json')?'application/json':path.endsWith('.svg')?'image/svg+xml':path.endsWith('.html')?'text/html':'application/octet-stream';
      return route.fulfill({body,contentType:type});
    } catch { return route.fulfill({status:404,body:'Not found'}); }
  });
  if(seed)await context.addInitScript(({gameId})=>{
    if(location.protocol!=='http:')return;
    if(localStorage.getItem('fixture-seeded'))return;
    localStorage.setItem('fixture-seeded','yes');
    localStorage.setItem('retro-library.collection.v1',JSON.stringify({schemaVersion:1,pinnedSystems:['snes'],entries:{[gameId]:{favorite:true,owned:true,status:'completed'}}}));
    localStorage.setItem('playnite-overrides',JSON.stringify({'sample-super-metroid':{notes:'Fixture owned note'}}));
    localStorage.setItem('steam-wishlist-notes',JSON.stringify({'900000001':'Fixture personal wish note'}));
    localStorage.setItem('sample:playnite-overrides',JSON.stringify({'sample-super-metroid':{notes:'Fixture sample note'}}));
  },{gameId});
  return context;
}
